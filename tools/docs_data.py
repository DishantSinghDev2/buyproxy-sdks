#!/usr/bin/env python3
"""docs_data.py <out.ts> — builds the website's SDK docs data from readme_gen.py (+ docs_extra.py)."""
import sys, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from readme_gen import L
from docs_extra import X

order = ["node", "python", "go", "php", "ruby", "java", "dotnet", "rust"]
out = []
for key in order:
    d, x = L[key], X[key]
    out.append({
        "key": key, "slug": x["slug"], "name": x["short"], "mono": x["mono"], "codeLang": x["lang"],
        "pkg": d["pkg"], "repo": d["repo"], "requires": d["requires"], "runtimeNote": x["runtime_note"],
        "install": d["install"], "features": d["features"],
        "auth": x["auth"], "quickstart": d["quickstart"], "targeting": x["targeting"], "account": x["account"],
        "frameworks": [{"title": t, "body": c} for t, c in d["frameworks"]],
        "payments": d["payments"], "reseller": d["reseller"], "errors": d["errors"], "errorsTable": x["errors_table"],
        "config": d["config"], "testing": x["testing"], "concurrency": x["concurrency"],
        "api": [{"capability": a, "call": b} for a, b in d["api"]], "notes": x["notes"], "dev": d["dev"],
    })
header = '''// GENERATED by buyproxy-sdks/tools/docs_data.py from the same source as the SDK READMEs — edit the tools, not this file.
export interface SdkFramework { title: string; body: string }
export interface SdkApiRow { capability: string; call: string }
export interface SdkDoc {
  key: string; slug: string; name: string; mono: string; codeLang: string; pkg: string; repo: string;
  requires: string; runtimeNote: string; install: string; features: string[];
  auth: string; quickstart: string; targeting: string; account: string; frameworks: SdkFramework[];
  payments: string; reseller: string; errors: string; errorsTable: string; config: string; testing: string;
  concurrency: string; api: SdkApiRow[]; notes: string[]; dev: string;
}

export const SDK_DOCS: SdkDoc[] = '''
pathlib.Path(sys.argv[1]).write_text(header + json.dumps(out, indent=2, ensure_ascii=False) + ";\n")
if len(sys.argv) > 2:
    nav = [{"slug": d["slug"], "name": d["name"]} for d in out]
    pathlib.Path(sys.argv[2]).write_text("// GENERATED by tools/docs_data.py — small on purpose: this is imported by client-side search.\nexport const SDK_NAV: { slug: string; name: string }[] = " + json.dumps(nav, indent=2) + ";\n")
print("wrote", sys.argv[1], len(out), "languages")
